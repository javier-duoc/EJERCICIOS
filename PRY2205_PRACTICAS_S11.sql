--Eliminar tablas existentes
DROP TABLE emple CASCADE CONSTRAINTS;
DROP TABLE depart CASCADE CONSTRAINTS;

-- Creación de schema
CREATE TABLE depart (
    dept_no NUMBER PRIMARY KEY,
    dnombre VARCHAR2(50),
    loc VARCHAR2(50)
);

CREATE TABLE emple (
    emp_no NUMBER PRIMARY KEY,
    apellido VARCHAR2(50),
    oficio VARCHAR2(50),
    dir NUMBER,
    fecha_ingreso DATE,
    salario NUMBER(10,2),
    comision NUMBER(10,2),
    dept_no NUMBER,
    CONSTRAINT fk_emple_dept FOREIGN KEY (dept_no) REFERENCES depart(dept_no)
);

